const {app} = require('electron')
const fs=require('node:fs'), os=require('node:os'), path=require('node:path'), assert=require('node:assert/strict')
app.setPath('userData',fs.mkdtempSync(path.join(os.tmpdir(),'inventory-test-')))
app.whenReady().then(()=>{
  const database=require('../electron/db.cjs')
  const db=database.open(app.getPath('userData')), api=require('../electron/api.cjs')
  try {
    const g=api.itemGroup.list().find(g=>g.name==='22K Gold')
    const item=api.item.save({name:'Jhumka',item_type_id:g.item_type_id,item_group_id:g.id,design_id:null,weight_mode:'WEIGHT',uom:'GRAM',hsn:'7113',image:''})
    const insert=db.prepare(`INSERT INTO tag_stock(tag,item_id,gross_wt,net_wt,final_wt,purity,purchase_rate,category,location,shelf_tray,size,huid,status)
      VALUES (?,?,10,10,9.16,91.6,5000,?,?,?,?,?,?)`)
    db.transaction(()=>{
      for(let i=0;i<50000;i++)insert.run(`TAG${String(i).padStart(6,'0')}`,item,i%2?'Bridal':'Daily','Main',i%2?'A':'B','14',`H${i}`,i%5?'IN_STOCK':'SOLD')
    })()
    const query={status:'IN_STOCK',category:'Bridal',shelf_tray:'A',minWeight:6,maxWeight:10}
    const start=performance.now()
    const first=api.reports.stock({...query,page:1})
    assert.equal(first.rows.length,50)
    assert.equal(first.total,20000)
    assert.equal(first.totals.count,20000)
    assert.equal(first.totals.net_wt,200000)
    assert.equal(first.totals.cost_value,916000000)
    const second=api.reports.stock({...query,page:2})
    assert(!second.rows.some(r=>first.rows.some(a=>a.id===r.id)))
    const complete=api.reports.stock(query)
    assert.equal(complete.rows.length,20000,'export must include every match')
    assert.equal(complete.totals.cost_value,first.totals.cost_value)
    const grouped=api.reports.stock({...query,groupBy:'category',page:1})
    assert.equal(grouped.groups[0].count,20000)
    assert.equal(grouped.totals.count,20000)
    assert.equal(grouped.total,1)
    assert.equal(api.tagStock.page({search:'H49999',page:1}).rows[0].huid,'H49999')
    assert.equal(api.tagStock.page({search:'TAG049999',page:1}).rows[0].tag,'TAG049999')
    assert.equal(api.tagStock.page({search:'%',page:1}).total,0,'wildcards are literal')
    assert.equal(api.tagStock.page({search:"' OR 1=1 --",page:1}).total,0)
    assert.equal(api.tagStock.page({search:'absent',page:99}).page,1)
    assert.equal(api.tagStock.page({...query,page:9999}).page,400)
    assert.throws(()=>api.tagStock.page({minWeight:10,maxWeight:2}),/Minimum/)
    assert.throws(()=>api.tagStock.page({minWeight:'invalid'}),/numbers/)
    assert.equal(api.tagStock.page({huid:'MISSING',page:1}).total,0)
    assert.equal(api.tagStock.page({metal:'Silver',page:1}).total,0)
    const facets=api.tagStock.facets()
    assert.deepEqual(facets.category,['Bridal','Daily'])
    db.transaction(()=>{
      const ins=db.prepare(`INSERT INTO item(name,item_type_id,item_group_id) VALUES (?,?,?)`)
      for(let i=0;i<3000;i++)ins.run(`Design ${i}`,g.item_type_id,g.id)
    })()
    const master=api.item.page({page:1})
    assert.equal(master.rows.length,50)
    assert.equal(master.total,3001)
    assert.equal(api.item.page({search:'Jhumka',page:1}).rows[0].id,item)
    console.log(`PASS: 50,000 tags, 3,001 items; combined filters, page boundaries, all-match totals/export, groups, HUID and literal searches. Queries and assertions ${Math.round(performance.now()-start)}ms.`)
    app.exit(0)
  } catch(e){ console.error(e);app.exit(1) }
})
